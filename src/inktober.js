// Clave da palabra: ink-ANO-DÍA, por exemplo ink-2026-06
export const promptKey = (year, day) => `ink-${year}-${String(day).padStart(2, '0')}`
export function parsePrompt(key) {
  const m = /^ink-(\d{4})-(\d{2})$/.exec(key || '')
  if (!m) return null
  const year = +m[1], day = +m[2], list = INKTOBER[year]
  return list && list[day - 1] ? { year, day, words: list[day - 1] } : null
}
export const wordOf = (words, lang) => words[lang] || words.en
// Hoxe é Inktober? Devolve ano e día (en hora local), ou null.
export function inktoberToday(now = new Date()) {
  return now.getMonth() === 9 && INKTOBER[now.getFullYear()] ? { year: now.getFullYear(), day: now.getDate() } : null
}
